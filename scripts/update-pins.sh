#!/usr/bin/env bash
# Regenerate scripts/pins.sh: the mise and Nerd Fonts releases install.sh downloads before mise
# takes over, with their published SHA-256 checksums.
#   scripts/update-pins.sh                  newest releases at least $MIN_AGE_DAYS old (default 7)
#   scripts/update-pins.sh v2026.10.17 v3.5.1   specific versions
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"
MIN_AGE_DAYS="${MIN_AGE_DAYS:-7}"

api() {
  local auth=()
  [ -n "${GITHUB_TOKEN:-}" ] && auth=(-H "Authorization: Bearer $GITHUB_TOKEN")
  curl -fsSL "${auth[@]+"${auth[@]}"}" "https://api.github.com/repos/$1"
}

# newest non-prerelease tag of REPO published at least MIN_AGE_DAYS ago
latest_tag() {
  local cutoff
  cutoff="$(date -u -d "-$MIN_AGE_DAYS days" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -v "-${MIN_AGE_DAYS}d" +%Y-%m-%dT%H:%M:%SZ)"
  api "$1/releases?per_page=30" |
    jq -r --arg cutoff "$cutoff" '[.[] | select(.draft | not) | select(.prerelease | not) | select(.published_at <= $cutoff)][0].tag_name'
}

MISE_VERSION="${1:-$(latest_tag jdx/mise)}"
NERD_FONTS_VERSION="${2:-$(latest_tag ryanoasis/nerd-fonts)}"

mise_sums="$(curl -fsSL "https://github.com/jdx/mise/releases/download/$MISE_VERSION/SHASUMS256.txt")"
mise_sum() { awk -v f="./mise-$MISE_VERSION-$1.tar.gz" '$2 == f { print $1 }' <<<"$mise_sums"; }
font_sum="$(curl -fsSL "https://github.com/ryanoasis/nerd-fonts/releases/download/$NERD_FONTS_VERSION/SHA-256.txt" |
  awk '$2 == "JetBrainsMono.tar.xz" { print $1 }')"

{
  echo "# shellcheck shell=bash disable=SC2034 # sourced by install.sh"
  echo "# Generated by scripts/update-pins.sh; don't edit by hand."
  echo "# Downloads install.sh makes before mise takes over, with their published SHA-256 checksums."
  echo "MISE_VERSION=\"$MISE_VERSION\""
  for p in linux-x64 linux-arm64 linux-x64-musl linux-arm64-musl macos-x64 macos-arm64; do
    sum="$(mise_sum "$p")"
    [ -n "$sum" ] || { echo "no checksum for mise $MISE_VERSION $p" >&2; exit 1; }
    echo "MISE_SHA256_${p//-/_}=\"$sum\""
  done
  echo "NERD_FONTS_VERSION=\"$NERD_FONTS_VERSION\""
  [ -n "$font_sum" ] || { echo "no checksum for JetBrainsMono.tar.xz $NERD_FONTS_VERSION" >&2; exit 1; }
  echo "NERD_FONTS_SHA256=\"$font_sum\""
} >pins.sh.new
mv pins.sh.new pins.sh
echo "pinned mise $MISE_VERSION, Nerd Fonts $NERD_FONTS_VERSION"
